public class TarefasLoop {
    public static void main(String[] args) {
        for (int i = 1; i <= 5; i++)
            System.out.println("Número: " + i);
    }
        /* int i = 1; == início de contagem
           i <=5 == até que i seja igual ou menor que 5 == rodar o loop
           i++ == a cada volta, acrescentamos 1 à i

         */
}
